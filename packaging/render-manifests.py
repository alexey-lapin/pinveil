"""Renders the Homebrew formula and the Scoop manifest for a release.

    python3 render-manifests.py VERSION BASE_URL CHECKSUMS OUT_DIR

Both install only the CLI, from the `pinveil_*` archives; the server ships as the image
and the `pinveil-server_*` archives. BASE_URL is where the archives live: the GitHub release download URL, or a file:// URL
for testing. CHECKSUMS is the release's checksums.txt (`<sha256>  <archive>` lines).
Writes OUT_DIR/pinveil.rb and OUT_DIR/pinveil.json.
"""

import json
import pathlib
import sys

HOMEPAGE = "https://github.com/alexey-lapin/pinveil"
DESCRIPTION = "Zero-knowledge one-time secret sharing CLI"


def main(version, base_url, checksums, out_dir):
    sums = {}
    for line in pathlib.Path(checksums).read_text().splitlines():
        digest, name = line.split()
        sums[name.lstrip("*")] = digest

    def archive(os_name, arch, ext="tar.gz"):
        name = f"pinveil_{version}_{os_name}_{arch}.{ext}"
        if name not in sums:
            raise SystemExit(f"{name} is not in {checksums}")
        return f"{base_url.rstrip('/')}/{name}", sums[name]

    darwin_arm = archive("darwin", "arm64")
    linux_amd = archive("linux", "amd64")
    linux_arm = archive("linux", "arm64")
    windows_amd = archive("windows", "amd64", "zip")

    formula = f'''# typed: false
# frozen_string_literal: true

# Generated by packaging/render-manifests.py in alexey-lapin/pinveil. Do not edit.
class Pinveil < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "{darwin_arm[0]}"
      sha256 "{darwin_arm[1]}"
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "{linux_amd[0]}"
      sha256 "{linux_amd[1]}"
    end
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "{linux_arm[0]}"
      sha256 "{linux_arm[1]}"
    end
  end

  def install
    bin.install "pinveil"
  end

  test do
    assert_match "pinveil {version}", shell_output("#{{bin}}/pinveil --version")
  end
end
'''
    manifest = {
        "version": version,
        "architecture": {
            "64bit": {
                "url": windows_amd[0],
                "bin": ["pinveil.exe"],
                "hash": windows_amd[1],
            }
        },
        "homepage": HOMEPAGE,
        "license": "MIT",
        "description": DESCRIPTION,
    }
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "pinveil.rb").write_text(formula)
    (out / "pinveil.json").write_text(json.dumps(manifest, indent=4) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:5])
